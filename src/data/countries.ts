// Bundled fallback country records.
//
// These are used when the REST Countries API is unavailable (offline, rate
// limited, or blocked) and as the baseline that remote data is merged into.
// The shape intentionally matches the fields consumed by the Country page.

export type CountryName = {
  common: string
  official: string
}

export type CountryFlags = {
  svg?: string
  png?: string
  alt?: string
}

export type CountryCurrency = {
  name: string
  symbol?: string
}

export type CountryMaps = {
  googleMaps?: string
  openStreetMaps?: string
}

export type CountryRecord = {
  cca3: string
  cca2?: string
  name: CountryName
  capital?: string[]
  region?: string
  subregion?: string
  population?: number
  area?: number
  flags?: CountryFlags
  latlng?: [number, number]
  languages?: Record<string, string>
  currencies?: Record<string, CountryCurrency>
  timezones?: string[]
  borders?: string[]
  tld?: string[]
  independent?: boolean
  unMember?: boolean
  landlocked?: boolean
  startOfWeek?: string
  maps?: CountryMaps
}

export function flagUrls(cca2: string, name: string): CountryFlags {
  const code = cca2.toLowerCase()
  return {
    svg: `https://flagcdn.com/${code}.svg`,
    png: `https://flagcdn.com/w320/${code}.png`,
    alt: `Flag of ${name}`,
  }
}

