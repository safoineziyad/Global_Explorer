const DICTS: Record<Locale, FeatureDict> = { en, fr, ar }

/** Translate a new-feature key, falling back to English then the raw key. */
function featureTranslate(
  locale: Locale,
  key: string,
  params?: FeatureParams
): string {
  const template = DICTS[locale]?.[key] ?? en[key] ?? key
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = params[name]
    return value === undefined ? match : String(value)
  })
}

/** Hook mirroring `useT`, for the additive feature strings. */
export function useFeaturesT(): FeatureTranslate {
  const { locale } = useI18n()
  return useCallback<FeatureTranslate>(
    (key, params) => featureTranslate(locale, key, params),
    [locale]
  )
}
